export function matchContactAssistTopic(text: string): ContactAssistTopic {
  const q = text.trim().toLowerCase();

  const rules: { test: RegExp; id: string }[] = [
    { test: /نصب|احداث|پشت.?بام|ندارم/, id: "install" },
    { test: /پرداخت|تسویه|واریز|صورت.?حساب|پول/, id: "payout" },
    { test: /فنی|خراب|اینورتر|افت|شستشو|نگهداری/, id: "support" },
    { test: /قرارداد|مدرک|مجوز/, id: "contract" },
    { test: /دولت|مقایسه|بورس|نرخ|قیمت/, id: "compare" },
    { test: /فروش|نیروگاه|برق/, id: "sell" },
  ];

  for (const rule of rules) {
    if (rule.test.test(q)) {
      const found = CONTACT_ASSIST_TOPICS.find((t) => t.id === rule.id);
      if (found) return found;
    }
  }

  return {
    id: "generic",
    label: "پیام عمومی",
    subject: "other",
    promptHint: text,
    reply: "یک متن عمومی آماده کردم؛ اگر موضوع دقیق‌تری داری از گزینه‌ها انتخاب کن.",
    message: `سلام،\n\n${text.trim()}\n\nلطفاً در اسرع وقت راهنمایی کنید. آماده ارائه اطلاعات تکمیلی هستم.\nبا تشکر`,
  };
}
