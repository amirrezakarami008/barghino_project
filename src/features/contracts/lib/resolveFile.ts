import type { Contract, ContractFile } from "../types";
import { buildSeedPdfBlob, getFileBlob } from "./files";

export async function resolveContractFileBlob(
  contract: Contract,
  file: ContractFile,
): Promise<Blob | null> {
  if (file.storageKey) {
    return getFileBlob(file.storageKey);
  }

  if (file.isSeed) {
    return buildSeedPdfBlob(contract.title, [
      `Bill account: ${contract.billAccount}`,
      `Type: ${contract.type}`,
      `Period: ${contract.startDate} - ${contract.endDate}`,
      `Volume: ${contract.volume}`,
      `Rate: ${contract.rate}`,
      `Status: ${contract.status}`,
      `File: ${file.name}`,
      `Version: ${file.version}`,
      "Generated by Barghma demo frontend",
    ]);
  }

  return null;
}
