from __future__ import annotations

from django.core.validators import RegexValidator
from rest_framework import serializers

from apps.accounts.api.serializers import UserSerializer
from apps.contracts.models import Contract, ContractHistory


class ContractDraftCreateSerializer(serializers.Serializer):
    plant_uuid = serializers.UUIDField()
    plan_uuid = serializers.UUIDField()


class ContractSignSerializer(serializers.Serializer):
    accepted_terms = serializers.BooleanField(
        help_text="Must be true to confirm acceptance of the displayed contract terms."
    )
    terms_version = serializers.CharField(max_length=64, allow_blank=False)
    terms_sha256 = serializers.CharField(
        max_length=64,
        validators=[RegexValidator(r"^[0-9a-fA-F]{64}$", "Enter a 64-character SHA-256 digest.")],
        help_text="SHA-256 digest generated by the client for the displayed contract document.",
    )
    signature_file_uuid = serializers.UUIDField(
        help_text=(
            "UUID of the signer's private PNG, JPEG, or WebP file uploaded for purpose=contract."
        )
    )

    def validate_accepted_terms(self, value: bool) -> bool:
        if value is not True:
            raise serializers.ValidationError("You must accept the contract terms to sign.")
        return value

    def validate_terms_version(self, value: str) -> str:
        value = value.strip()
        if not value:
            raise serializers.ValidationError("A terms version is required.")
        return value


class ContractReviewSerializer(serializers.Serializer):
    decision = serializers.ChoiceField(choices=("approved", "rejected"))
    reason = serializers.CharField(max_length=1000, allow_blank=True, required=False, default="")

    def validate(self, attrs: dict) -> dict:
        if attrs["decision"] == "rejected" and not attrs["reason"].strip():
            raise serializers.ValidationError({"reason": "A reason is required when rejecting."})
        attrs["reason"] = attrs["reason"].strip()
        return attrs


class ContractHistorySerializer(serializers.ModelSerializer):
    class Meta:
        model = ContractHistory
        fields = (
            "uuid",
            "event_type",
            "from_status",
            "to_status",
            "actor_uuid",
            "details",
            "created_at",
        )
        read_only_fields = fields


class ContractSerializer(serializers.ModelSerializer):
    plant_uuid = serializers.UUIDField(source="plant.uuid", read_only=True, allow_null=True)
    plant_name = serializers.CharField(source="plant.name", read_only=True, allow_null=True)
    plant_capacity_kwp = serializers.DecimalField(
        source="plant.capacity_kwp",
        max_digits=8,
        decimal_places=3,
        coerce_to_string=False,
        read_only=True,
        allow_null=True,
    )
    branch_uuid = serializers.UUIDField(source="plant.branch.uuid", read_only=True, allow_null=True)
    meter_number = serializers.CharField(
        source="plant.branch.meter_number", read_only=True, allow_null=True
    )
    branch_address = serializers.CharField(
        source="plant.branch.address", read_only=True, allow_null=True
    )
    plan_uuid = serializers.UUIDField(source="plan.uuid", read_only=True, allow_null=True)
    seller_identity = serializers.SerializerMethodField()
    signature_file_uuid = serializers.UUIDField(
        source="signature_file.uuid", read_only=True, allow_null=True
    )
    history = ContractHistorySerializer(many=True, read_only=True)
    commitment_kwh = serializers.DecimalField(
        max_digits=14,
        decimal_places=3,
        coerce_to_string=False,
        read_only=True,
        allow_null=True,
    )
    rate_toman_per_kwh = serializers.DecimalField(
        max_digits=14,
        decimal_places=3,
        coerce_to_string=False,
        read_only=True,
        allow_null=True,
    )

    class Meta:
        model = Contract
        fields = (
            "uuid",
            "status",
            "terms_version",
            "terms_sha256",
            "signed_at",
            "signature_file_uuid",
            "review_decision",
            "reviewed_at",
            "reviewed_by_uuid",
            "review_note",
            "plant_uuid",
            "plant_name",
            "plant_capacity_kwp",
            "branch_uuid",
            "meter_number",
            "branch_address",
            "seller_identity",
            "plan_uuid",
            "plan_name",
            "commitment_kwh",
            "rate_toman_per_kwh",
            "created_at",
            "updated_at",
            "history",
        )
        read_only_fields = fields

    def get_seller_identity(self, contract: Contract) -> dict | None:
        snapshot = self._signed_snapshot(contract)
        if snapshot is not None:
            return snapshot.get("seller")
        return UserSerializer(contract.owner).data.get("identity_profile")

    @staticmethod
    def _signed_snapshot(contract: Contract) -> dict | None:
        if contract.signed_at is None:
            return None
        for event in contract.history.all():
            if event.event_type == ContractHistory.EventType.SIGNED:
                snapshot = event.details.get("contract_snapshot")
                if isinstance(snapshot, dict):
                    return snapshot
        return None

    def to_representation(self, instance: Contract) -> dict:
        data = super().to_representation(instance)
        snapshot = self._signed_snapshot(instance)
        if snapshot is None:
            return data
        # These fields describe the accepted version, not today's mutable site/profile.
        plant = snapshot.get("plant", {})
        branch = snapshot.get("branch", {})
        terms = snapshot.get("commercial_terms", {})
        data.update(
            plant_uuid=plant.get("uuid"),
            plant_name=plant.get("name"),
            plant_capacity_kwp=self.fields["plant_capacity_kwp"].to_representation(
                plant.get("capacity_kwp")
            )
            if plant.get("capacity_kwp") is not None
            else None,
            branch_uuid=branch.get("uuid"),
            meter_number=branch.get("meter_number"),
            branch_address=branch.get("address"),
            seller_identity=snapshot.get("seller"),
            plan_uuid=terms.get("plan_uuid"),
            plan_name=terms.get("plan_name"),
        )
        return data
